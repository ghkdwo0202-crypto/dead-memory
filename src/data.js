export function compatible(organID, mutationID) {
  const o = ORGANS[organID],
    m = MUTATIONS[mutationID];
  return Boolean(
    o &&
      m &&
      o.availableMutations.includes(m.id) &&
      m.compatibleTags.some((t) => o.tags.includes(t)),
  );
}
